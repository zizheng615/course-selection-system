-- =============================================================================
-- 6. 选课记录（演示数据）
--    规则：按 (student_id * 7 + course_id * 3) % 11 < 2 生成，可复现。
-- =============================================================================
INSERT INTO enrollment (student_id, course_id, status, selected_at)
SELECT s.id,
       c.id,
       'SELECTED',
       datetime('now', 'localtime', '-' || ((s.id * 3 + c.id) % 30) || ' days')
FROM student s
JOIN course c
  ON ((s.id * 7 + c.id * 3) % 11) < 2
WHERE c.semester = '2026-2027-1';

-- 为部分已选记录录入成绩，便于演示「成绩查询」
UPDATE enrollment
SET score = ROUND(55 + ((id * 37) % 45) + 0.5, 1)
WHERE id % 3 = 0;


-- =============================================================================
-- 7. 同步 enrolled_count
--    enrolled_count 是反范式字段，批量导入后必须与选课记录对齐，
--    否则会破坏 chk_capacity 约束所依赖的一致性。
-- =============================================================================
UPDATE course
SET enrolled_count = (
    SELECT COUNT(*)
    FROM enrollment e
    WHERE e.course_id = course.id AND e.status = 'SELECTED'
);


