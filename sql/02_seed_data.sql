-- 8. 数据校验
-- =============================================================================
SELECT '用户' AS entity, COUNT(*) AS cnt FROM sys_user
UNION ALL SELECT '教师', COUNT(*) FROM teacher
UNION ALL SELECT '学生', COUNT(*) FROM student
UNION ALL SELECT '课程', COUNT(*) FROM course
UNION ALL SELECT '上课时间', COUNT(*) FROM course_schedule
UNION ALL SELECT '选课记录', COUNT(*) FROM enrollment
UNION ALL SELECT '已录成绩', COUNT(*) FROM enrollment WHERE score IS NOT NULL;

-- 容量一致性校验（应为 0 行）
SELECT c.id, c.name, c.capacity, c.enrolled_count,
       (SELECT COUNT(*) FROM enrollment e
        WHERE e.course_id = c.id AND e.status = 'SELECTED') AS actual
FROM course c
WHERE c.enrolled_count <> (SELECT COUNT(*) FROM enrollment e
                           WHERE e.course_id = c.id AND e.status = 'SELECTED');
